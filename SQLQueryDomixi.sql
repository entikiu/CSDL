SELECT TB.TEN_TB, L.TEN_LOAI, NH.TEN_NSX, TB.MODEL, TB.NAM_SX
FROM PH_PHOI_TB PP, MON_TB MT, THIET_BI TB, LOAI_TB L, NHAN_HIEU NH
WHERE PP.MA_MON = MT.MA_MON
  AND MT.MA_TB = TB.MA_TB
  AND TB.MA_LOAI = L.MA_LOAI
  AND TB.MA_NHHIEU = NH.MA_NSX
  AND PP.NGAY_KT IS NOT NULL
  AND DATEDIFF(DAY, PP.NGAY_BD, PP.NGAY_KT) = (
      SELECT MAX(DATEDIFF(DAY, NGAY_BD, NGAY_KT))
      FROM PH_PHOI_TB
      WHERE NGAY_KT IS NOT NULL
  );

  --cau 9
SELECT SUM(TRI_GIA) AS TONG_TRI_GIA
FROM THANH_LY
WHERE NGAY_GIO >= '2007-11-01' 
  AND NGAY_GIO < '2008-01-01';

