SELECT TB.MODEL, TB.TEN_TB
FROM THIET_BI TB, MON_TB MT, PH_PHOI_TB PP, PHG_DV PD, DON_VI DV, KHAU_HAO KH
WHERE TB.MA_TB = MT.MA_TB
  AND MT.MA_MON = PP.MA_MON
  AND PP.MA_PHONG = PD.MA_PHONG
  AND PD.MA_DV = DV.MA_DV
  AND MT.MA_MON = KH.MA_MON
  AND DV.TEN_DV = N'Phòng Nghiên cứu và Phát triển' 
  AND KH.NGAY >= DATEADD(YEAR, 1, MT.NGAY_MUA)
GROUP BY TB.MODEL, TB.TEN_TB, MT.MA_MON
HAVING AVG(KH.TY_LE_KH) > 0.9;

